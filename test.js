import assert from 'node:assert/strict';
import staircase from './01-staircase.js';
import gradingStudents from './02-grading-students.js';
import timeConversion from './03-time-conversion.js';
import repeatStr from './04-string-repeat.js';
import solution from './05-reversed-strings.js';
import positiveSum from './06-sum-of-positive.js';
import summation from './07-grasshopper-summation.js';
import booleanToString from './08-boolean-to-string.js';
import fizzBuzz from './09-fizz-buzz.js';
import runningSum from './10-running-sum.js';
import maximumWealth from './11-richest-customer-wealth.js';
import removeDuplicates from './12-remove-duplicates-sorted-array.js';
import containsDuplicate from './13-contains-duplicate.js';
import moveZeroes from './14-move-zeroes.js';
import merge from './15-merge-sorted-array.js';
import threeSum from './16-three-sum.js';
import plusOne from './17-plus-one.js';
import reverseString from './18-reverse-string.js';
import lengthOfLastWord from './19-length-of-last-word.js';
import longestCommonPrefix from './20-longest-common-prefix.js';

const eq = assert.deepStrictEqual;
eq(staircase(4), '   #\n  ##\n ###\n####');
eq(staircase(1), '#');
eq(gradingStudents([73, 67, 38, 33]), [75, 67, 40, 33]);
eq(timeConversion('12:00:00AM'), '00:00:00');
eq(timeConversion('07:05:45PM'), '19:05:45');
eq(timeConversion('12:30:45PM'), '12:30:45');
eq(repeatStr(3, 'ha'), 'hahaha');
eq(repeatStr(0, 'hello'), '');
eq(solution('world'), 'dlrow');
eq(solution(''), '');
eq(positiveSum([1, -4, 7, 12]), 20);
eq(positiveSum([]), 0);
eq(summation(8), 36);
eq(booleanToString(false), 'false');
eq(fizzBuzz(15).pop(), 'FizzBuzz');
eq(runningSum([1, 2, 3, 4]), [1, 3, 6, 10]);
eq(maximumWealth([[1, 5], [7, 3], [3, 5]]), 10);
let a = [0, 0, 1, 1, 1, 2, 2, 3, 3, 4];
const k = removeDuplicates(a);
eq([k, a.slice(0, k)], [5, [0, 1, 2, 3, 4]]);
eq(containsDuplicate([1, 2, 3, 4]), false);
eq(containsDuplicate([1, 2, 3, 1]), true);
a = [0, 1, 0, 3, 12]; moveZeroes(a); eq(a, [1, 3, 12, 0, 0]);
a = [1, 2, 3, 0, 0, 0]; merge(a, 3, [2, 5, 6], 3); eq(a, [1, 2, 2, 3, 5, 6]);
a = [0]; merge(a, 0, [1], 1); eq(a, [1]);
eq(threeSum([-1, 0, 1, 2, -1, -4]), [[-1, -1, 2], [-1, 0, 1]]);
eq(threeSum([0, 0, 0]), [[0, 0, 0]]);
eq(threeSum([0, 1, 1]), []);
eq(plusOne([9, 9, 9]), [1, 0, 0, 0]);
eq(plusOne([1, 2, 9]), [1, 3, 0]);
a = ['h', 'e', 'l', 'l', 'o']; reverseString(a); eq(a, ['o', 'l', 'l', 'e', 'h']);
eq(lengthOfLastWord('   fly me   to   the moon  '), 4);
eq(longestCommonPrefix(['flower', 'flow', 'flight']), 'fl');
eq(longestCommonPrefix(['dog', 'racecar', 'car']), '');
console.log('separate files: all passed');
